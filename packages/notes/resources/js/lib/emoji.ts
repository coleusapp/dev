/**
 * Emoji whose name contains every word of the query.
 */
export const searchEmoji = (query: string): Emoji[] => {
    const words = query.toLowerCase().split(/\s+/).filter(Boolean);

    return EMOJI_GROUPS.flatMap((group) => group.emoji).filter((emoji) => words.every((word) => emoji.name.includes(word)));
};
